void RecipeManager::addRecipe(QString name, QString category, QString ingredients, QString text) {
    Recipe r;
    r.id = recipes.size();
    r.name = name;
    r.category = category;
    r.ingredients = ingredients;
    r.text = text;
    recipes.append(r);
}

QVector<Recipe> RecipeManager::findRecipes(QString searchText, QString category) {
    QVector<Recipe> result;
    for (int i = 0; i < recipes.size(); i++) {
        bool okCategory = (category == "Все" || recipes[i].category == category);
        bool okText = searchText.isEmpty() ||
                      recipes[i].name.contains(searchText, Qt::CaseInsensitive) ||
                      recipes[i].ingredients.contains(searchText, Qt::CaseInsensitive);

        if (okCategory && okText) {
            result.append(recipes[i]);
        }
    }
    for (int i = 0; i < result.size() - 1; i++) {
        for (int j = 0; j < result.size() - i - 1; j++) {
            if (result[j].name > result[j + 1].name) {
                Recipe temp = result[j];
                result[j] = result[j + 1];
                result[j + 1] = temp;
            }
        }
    }

    return result;
}

void RecipeManager::setDayMeal(int dayIndex, QString mealName) {
    if (dayIndex >= 0 && dayIndex < 7) {
        weekMenu[dayIndex] = mealName;
    }
}
